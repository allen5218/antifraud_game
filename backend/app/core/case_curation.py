def is_safe_narrative(text: str, title: str = "") -> bool:
    """檢查題目內容與標題是否包含任何結局洩題關鍵詞。"""
    combined = f"{title} {text}"
    return not any(keyword in combined for keyword in SPOILER_KEYWORDS)


def get_safe_case_projection(case_id: int) -> SafeCaseProjection | None:
    """依 case_id 取得已審核的策展投影；若無策展紀錄則回傳 None。"""
    return SAFE_CURATED_PROJECTIONS.get(case_id)


def project_case_safely(
    case: GameCaseRow,
) -> tuple[SafeCaseProjection | None, bool]:
    """將資料庫 GameCaseRow 安全投影為玩家可見素材。

    回傳: (投影結果, 是否安全可用)
    若缺少安全投影且原案例含洩題結局，則嚴格判定為不可用（安全攔截）。
    """
    if case.id in SAFE_CURATED_PROJECTIONS:
        return SAFE_CURATED_PROJECTIONS[case.id], True

    # 未在策展名冊中的歷史案例：進行嚴格安全檢查
    if not is_safe_narrative(case.narrative, case.title):
        # 包含洩題關鍵詞且無策展覆蓋：嚴禁將未過濾結局呈現在玩家面前
        return None, False

    # 內容本身無洩題詞彙，可作為動態投影
    dynamic = SafeCaseProjection(
        case_id=case.id,
        case_key=f"dynamic-{case.id}",
        fraud_type=case.fraud_type,
        is_scam=case.is_scam,
        title=case.title,
        narrative=case.narrative,
        is_curated=False,
    )
    return dynamic, True
