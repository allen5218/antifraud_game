def _oauth_user(db: Session) -> User:
    """LINE 登入建立的帳號：email 是系統產生的內部格式（oauth.py）"""
    user = User(
        email=f"line-{uuid.uuid4().hex}@oauth.invalid", hashed_password="unusable"
    )
    db.add(user)
    db.commit()
    db.refresh(user)
    return user


